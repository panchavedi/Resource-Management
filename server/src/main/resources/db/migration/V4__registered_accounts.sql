CREATE TABLE registered_accounts (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(40) NOT NULL,
    display_name VARCHAR(120) NOT NULL,
    password_hash VARCHAR(255) NOT NULL,
    status VARCHAR(24) NOT NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    reviewed_at TIMESTAMPTZ,
    reviewed_by VARCHAR(80),
    CONSTRAINT uq_registered_accounts_username UNIQUE (username),
    CONSTRAINT ck_registered_accounts_status CHECK (status IN ('PENDING_APPROVAL', 'ACTIVE', 'REJECTED'))
);
CREATE INDEX ix_registered_accounts_status ON registered_accounts (status, requested_at);
