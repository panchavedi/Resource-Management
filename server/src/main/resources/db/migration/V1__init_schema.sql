-- =====================================================================================
-- Talent Management – core schema
-- Conventions: surrogate BIGINT identity keys, natural keys enforced with UNIQUE,
-- enums stored as VARCHAR with CHECK constraints, all timestamps TIMESTAMPTZ (UTC).
-- =====================================================================================

-- ---------------------------------------------------------------- employees
CREATE TABLE employees (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_code     VARCHAR(20)  NOT NULL,
    name              VARCHAR(120) NOT NULL,
    email             VARCHAR(160) NOT NULL,
    job_title         VARCHAR(120),
    department        VARCHAR(80)  NOT NULL,
    location          VARCHAR(80),                 -- NULL = not recorded; disclosed, never guessed
    remote_eligible   BOOLEAN      NOT NULL DEFAULT FALSE,
    employment_status VARCHAR(20)  NOT NULL,
    capacity_percent  INTEGER      NOT NULL DEFAULT 100,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version           BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_employees_code  UNIQUE (employee_code),
    CONSTRAINT uq_employees_email UNIQUE (email),
    CONSTRAINT ck_employees_status   CHECK (employment_status IN ('ACTIVE', 'BENCH', 'ON_LEAVE', 'INACTIVE')),
    CONSTRAINT ck_employees_capacity CHECK (capacity_percent BETWEEN 1 AND 100)
);
CREATE INDEX ix_employees_department ON employees (department);
CREATE INDEX ix_employees_status     ON employees (employment_status);
CREATE INDEX ix_employees_location   ON employees (lower(location));

-- ---------------------------------------------------------------- skills
CREATE TABLE skills (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(80)  NOT NULL,
    category    VARCHAR(60)  NOT NULL,
    description VARCHAR(500),
    created_at  TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at  TIMESTAMPTZ  NOT NULL DEFAULT now()
);
CREATE UNIQUE INDEX uq_skills_name_ci ON skills (lower(name));
CREATE INDEX ix_skills_category ON skills (category);

-- ---------------------------------------------------------------- employee_skills
CREATE TABLE employee_skills (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id       BIGINT       NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    skill_id          BIGINT       NOT NULL REFERENCES skills (id),
    proficiency_level INTEGER      NOT NULL,
    evidence          VARCHAR(500),
    evidence_source   VARCHAR(30)  NOT NULL,
    last_validated_at DATE,                         -- NULL = never validated (disclosed as unvalidated)
    validated_by      VARCHAR(80),
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT uq_employee_skills UNIQUE (employee_id, skill_id),
    CONSTRAINT ck_employee_skills_level  CHECK (proficiency_level BETWEEN 1 AND 5),
    CONSTRAINT ck_employee_skills_source CHECK (evidence_source IN
        ('CERTIFICATION', 'ASSESSMENT', 'PROJECT_DELIVERY', 'MANAGER_REVIEW', 'SELF_DECLARED'))
);
CREATE INDEX ix_employee_skills_skill_level ON employee_skills (skill_id, proficiency_level);

-- ---------------------------------------------------------------- project_demands
CREATE TABLE project_demands (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_name       VARCHAR(120)  NOT NULL,
    role               VARCHAR(120)  NOT NULL,
    description        VARCHAR(2000),
    start_date         DATE          NOT NULL,
    end_date           DATE          NOT NULL,
    location           VARCHAR(80),                -- NULL = location-agnostic
    remote_allowed     BOOLEAN       NOT NULL DEFAULT FALSE,
    allocation_percent INTEGER       NOT NULL,
    headcount          INTEGER       NOT NULL DEFAULT 1,
    priority           VARCHAR(10)   NOT NULL,
    status             VARCHAR(20)   NOT NULL,
    created_by         VARCHAR(80)   NOT NULL,
    created_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    updated_at         TIMESTAMPTZ   NOT NULL DEFAULT now(),
    version            BIGINT        NOT NULL DEFAULT 0,
    CONSTRAINT ck_demands_dates     CHECK (end_date >= start_date),
    CONSTRAINT ck_demands_percent   CHECK (allocation_percent BETWEEN 1 AND 100),
    CONSTRAINT ck_demands_headcount CHECK (headcount BETWEEN 1 AND 50),
    CONSTRAINT ck_demands_priority  CHECK (priority IN ('CRITICAL', 'HIGH', 'MEDIUM', 'LOW')),
    CONSTRAINT ck_demands_status    CHECK (status IN ('OPEN', 'PARTIALLY_FILLED', 'FILLED', 'CANCELLED'))
);
CREATE INDEX ix_demands_status_priority ON project_demands (status, priority);
CREATE INDEX ix_demands_role            ON project_demands (lower(role));
CREATE INDEX ix_demands_dates           ON project_demands (start_date, end_date);

-- ---------------------------------------------------------------- demand_skills
CREATE TABLE demand_skills (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id           BIGINT   NOT NULL REFERENCES project_demands (id) ON DELETE CASCADE,
    skill_id            BIGINT   NOT NULL REFERENCES skills (id),
    minimum_proficiency INTEGER NOT NULL,
    mandatory           BOOLEAN  NOT NULL DEFAULT TRUE,
    CONSTRAINT uq_demand_skills UNIQUE (demand_id, skill_id),
    CONSTRAINT ck_demand_skills_level CHECK (minimum_proficiency BETWEEN 1 AND 5)
);
CREATE INDEX ix_demand_skills_skill ON demand_skills (skill_id);

-- ---------------------------------------------------------------- allocations
CREATE TABLE allocations (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id         BIGINT       NOT NULL REFERENCES employees (id),
    demand_id           BIGINT       NOT NULL REFERENCES project_demands (id),
    start_date          DATE         NOT NULL,
    end_date            DATE         NOT NULL,
    allocation_percent  INTEGER      NOT NULL,
    status              VARCHAR(20)  NOT NULL,
    requested_by        VARCHAR(80)  NOT NULL,
    requested_at        TIMESTAMPTZ  NOT NULL,
    request_note        VARCHAR(500),
    decided_by          VARCHAR(80),
    decided_at          TIMESTAMPTZ,
    decision_note       VARCHAR(500),
    cancelled_by        VARCHAR(80),
    cancelled_at        TIMESTAMPTZ,
    cancellation_reason VARCHAR(500),
    idempotency_key     VARCHAR(80),
    created_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at          TIMESTAMPTZ  NOT NULL DEFAULT now(),
    version             BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_allocations_idempotency UNIQUE (idempotency_key),
    CONSTRAINT ck_allocations_dates   CHECK (end_date >= start_date),
    CONSTRAINT ck_allocations_percent CHECK (allocation_percent BETWEEN 1 AND 100),
    CONSTRAINT ck_allocations_status  CHECK (status IN ('PENDING_APPROVAL', 'APPROVED', 'REJECTED', 'CANCELLED'))
);
-- At most one capacity-holding allocation per employee and demand (last line of defence).
CREATE UNIQUE INDEX uq_allocation_active_employee_demand
    ON allocations (employee_id, demand_id) WHERE status IN ('PENDING_APPROVAL', 'APPROVED');
-- Overlap lookups only ever consider capacity-holding rows.
CREATE INDEX ix_allocations_employee_active_dates
    ON allocations (employee_id, start_date, end_date) WHERE status IN ('PENDING_APPROVAL', 'APPROVED');
CREATE INDEX ix_allocations_demand_status ON allocations (demand_id, status);
CREATE INDEX ix_allocations_status        ON allocations (status);

-- ---------------------------------------------------------------- allocation_events (append-only history)
CREATE TABLE allocation_events (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    allocation_id BIGINT       NOT NULL REFERENCES allocations (id),
    event_type    VARCHAR(20)  NOT NULL,
    from_status   VARCHAR(20),
    to_status     VARCHAR(20)  NOT NULL,
    actor         VARCHAR(80)  NOT NULL,
    note          VARCHAR(500),
    occurred_at   TIMESTAMPTZ  NOT NULL,
    CONSTRAINT ck_allocation_events_type CHECK (event_type IN ('REQUESTED', 'APPROVED', 'REJECTED', 'CANCELLED'))
);
CREATE INDEX ix_allocation_events_allocation ON allocation_events (allocation_id, occurred_at);

-- ---------------------------------------------------------------- learning_resources (catalogue)
CREATE TABLE learning_resources (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    skill_id       BIGINT       NOT NULL REFERENCES skills (id) ON DELETE CASCADE,
    title          VARCHAR(160) NOT NULL,
    provider       VARCHAR(80)  NOT NULL,
    format         VARCHAR(20)  NOT NULL,
    target_level   INTEGER      NOT NULL,
    duration_hours INTEGER      NOT NULL,
    url            VARCHAR(300),
    CONSTRAINT ck_learning_resources_format CHECK (format IN ('COURSE', 'CERTIFICATION', 'LAB', 'MENTORING', 'PROJECT')),
    CONSTRAINT ck_learning_resources_level  CHECK (target_level BETWEEN 1 AND 5),
    CONSTRAINT ck_learning_resources_hours  CHECK (duration_hours > 0)
);
CREATE INDEX ix_learning_resources_skill ON learning_resources (skill_id, target_level);

-- ---------------------------------------------------------------- training_recommendations
CREATE TABLE training_recommendations (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    employee_id          BIGINT       NOT NULL REFERENCES employees (id) ON DELETE CASCADE,
    skill_id             BIGINT       NOT NULL REFERENCES skills (id),
    demand_id            BIGINT       REFERENCES project_demands (id) ON DELETE SET NULL,
    learning_resource_id BIGINT       REFERENCES learning_resources (id) ON DELETE SET NULL,
    current_level        INTEGER,
    target_level         INTEGER      NOT NULL,
    reason               VARCHAR(500) NOT NULL,
    source               VARCHAR(20)  NOT NULL,
    status               VARCHAR(20)  NOT NULL,
    created_by           VARCHAR(80)  NOT NULL,
    created_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at           TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_training_source CHECK (source IN ('AI_AGENT', 'MANUAL')),
    CONSTRAINT ck_training_status CHECK (status IN ('RECOMMENDED', 'IN_PROGRESS', 'COMPLETED', 'DISMISSED')),
    CONSTRAINT ck_training_levels CHECK (target_level BETWEEN 1 AND 5 AND (current_level IS NULL OR current_level BETWEEN 1 AND 5))
);
-- One open recommendation per employee and skill keeps the learning backlog free of duplicates.
CREATE UNIQUE INDEX uq_training_open_employee_skill
    ON training_recommendations (employee_id, skill_id) WHERE status IN ('RECOMMENDED', 'IN_PROGRESS');
CREATE INDEX ix_training_status ON training_recommendations (status);

-- ---------------------------------------------------------------- AI agent audit trail
CREATE TABLE ai_agent_runs (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    demand_id         BIGINT       REFERENCES project_demands (id) ON DELETE SET NULL,
    requested_by      VARCHAR(80)  NOT NULL,
    goal              VARCHAR(300) NOT NULL,
    question          VARCHAR(1000),
    mode              VARCHAR(20)  NOT NULL,
    model             VARCHAR(80),
    status            VARCHAR(30)  NOT NULL,
    narrative_source  VARCHAR(30),
    validation_passed BOOLEAN      NOT NULL DEFAULT FALSE,
    llm_attempts      INTEGER      NOT NULL DEFAULT 0,
    validation_issues JSONB,
    response          JSONB,
    error_message     VARCHAR(1000),
    duration_ms       BIGINT       NOT NULL DEFAULT 0,
    created_at        TIMESTAMPTZ  NOT NULL DEFAULT now(),
    CONSTRAINT ck_ai_runs_mode   CHECK (mode IN ('LIVE', 'SIMULATED', 'AUTO')),
    CONSTRAINT ck_ai_runs_status CHECK (status IN ('COMPLETED', 'COMPLETED_WITH_FALLBACK', 'FAILED'))
);
CREATE INDEX ix_ai_runs_demand  ON ai_agent_runs (demand_id, created_at DESC);
CREATE INDEX ix_ai_runs_created ON ai_agent_runs (created_at DESC);

CREATE TABLE ai_tool_calls (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    run_id      BIGINT       NOT NULL REFERENCES ai_agent_runs (id) ON DELETE CASCADE,
    sequence_no INTEGER      NOT NULL,
    tool_name   VARCHAR(60)  NOT NULL,
    arguments   JSONB,
    summary     VARCHAR(1000),
    success     BOOLEAN      NOT NULL,
    duration_ms BIGINT       NOT NULL DEFAULT 0,
    CONSTRAINT uq_ai_tool_calls_sequence UNIQUE (run_id, sequence_no)
);
